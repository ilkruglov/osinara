/**
 * Zepp export reading: AES zip and CSV rows.
 *
 * Constructs covered:
 * - A WinZip AES archive made by pyzipper (not by this reader's inverse) decrypts with the right
 *   password, including a stored entry longer than 256 AES blocks (the counter carries past a byte).
 * - A missing or wrong password, a non-zip and an archive without the known folders are named.
 * - Activity, sleep and weigh-ins keep only real rows: zero days and nights are skipped, the
 *   backslash-escaped `naps` column does not break a row, a zero fat rate is no fat rate.
 *
 * Fixtures: `test/fixtures/health-journal/zepp-export-*.zip`, synthetic rows in the real export's format, generated by
 * `.tmp/zepp-fixture/make.py` (pyzipper 0.4.0, password `Zepp-2026`).
 */
import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import { parseZeppExport, ZeppExportError } from "./zepp-export.js";
import { buildZip } from "./zip-test-builder.js";

const fixture = (name: string) =>
  readFileSync(new URL(`../../../test/fixtures/health-journal/${name}`, import.meta.url));

describe("parseZeppExport", () => {
  it("decrypts the AES export and keeps only real rows", () => {
    const parsed = parseZeppExport(fixture("zepp-export-aes.zip"), "Zepp-2026");
    expect(parsed.activity).toEqual([
      { date: "2026-10-01", distanceM: 4810, steps: 8199 },
      { date: "2026-10-03", distanceM: 7300, steps: 10500 },
    ]);
    expect(parsed.sleep).toEqual([
      {
        awakeMin: 10,
        deepMin: 90,
        end: "2026-10-01T05:00:00Z",
        lightMin: 300,
        remMin: 60,
        start: "2026-09-30T21:30:00Z",
        totalMin: 450,
        wakeDate: "2026-10-01",
      },
      {
        awakeMin: 5,
        deepMin: 100,
        end: "2026-10-03T04:40:00Z",
        lightMin: 320,
        remMin: 50,
        start: "2026-10-02T20:45:00Z",
        totalMin: 470,
        wakeDate: "2026-10-03",
      },
    ]);
    expect(parsed.weighIns).toEqual([
      { bodyFatPct: 28.7, measuredAt: "2026-10-01T05:10:00Z", weightKg: 64.9 },
      { bodyFatPct: null, measuredAt: "2026-10-02T21:30:00Z", weightKg: 64.6 },
    ]);
  });

  it("reads the same rows from an unencrypted export", () => {
    const plain = parseZeppExport(fixture("zepp-export-plain.zip"), null);
    expect(plain).toEqual(parseZeppExport(fixture("zepp-export-aes.zip"), "Zepp-2026"));
  });

  it("decrypts an entry longer than 256 AES blocks", () => {
    const parsed = parseZeppExport(fixture("zepp-export-aes-large.zip"), "Zepp-2026");
    expect(parsed.activity).toHaveLength(400);
    expect(parsed.activity.at(-1)).toEqual({
      date: "2026-02-04",
      distanceM: 3500 + ((399 * 29) % 6000),
      steps: 5000 + ((399 * 37) % 9000),
    });
  });

  it("names a missing or wrong password and an unreadable archive", () => {
    const reason = (run: () => unknown) => {
      try {
        run();
      } catch (error) {
        return error instanceof ZeppExportError ? error.reason : String(error);
      }
      return "no error";
    };
    expect(reason(() => parseZeppExport(fixture("zepp-export-aes.zip"), null))).toBe(
      "password_required",
    );
    expect(reason(() => parseZeppExport(fixture("zepp-export-aes.zip"), "wrong"))).toBe(
      "password_wrong",
    );
    expect(reason(() => parseZeppExport(Buffer.from("not a zip at all"), null))).toBe("corrupt");
  });
});

const csv = (name: string, lines: string[]) => ({
  data: Buffer.from(`\ufeff${lines.join("\n")}\n`),
  name,
});
const ACTIVITY = "date,steps,distance,runDistance,calories";
const SLEEP = "date,deepSleepTime,shallowSleepTime,wakeTime,start,stop,REMTime,naps";
const BODY =
  "time,weight,height,bmi,fatRate,bodyWaterRate,boneMass,metabolism,muscleRate,visceralFat";

describe("parseZeppExport rows", () => {
  it("keeps one row per day when an export repeats a date, the later file winning", () => {
    const parsed = parseZeppExport(
      buildZip([
        csv("ACTIVITY/ACTIVITY_1.csv", [
          ACTIVITY,
          "2026-10-01,100,80,0,1",
          "2026-10-02,200,160,0,2",
        ]),
        csv("ACTIVITY/ACTIVITY_2.csv", [ACTIVITY, "2026-10-02,300,240,0,3"]),
        csv("SLEEP/SLEEP_1.csv", [
          SLEEP,
          "2026-10-02,60,200,0,2026-10-01 22:00:00+0000,2026-10-02 03:00:00+0000,40,",
          "2026-10-02,70,210,0,2026-10-01 22:00:00+0000,2026-10-02 03:30:00+0000,40,",
        ]),
      ]),
      null,
    );
    expect(parsed.activity).toEqual([
      { date: "2026-10-01", distanceM: 80, steps: 100 },
      { date: "2026-10-02", distanceM: 240, steps: 300 },
    ]);
    expect(parsed.sleep).toHaveLength(1);
    expect(parsed.sleep[0]).toMatchObject({ deepMin: 70, totalMin: 320 });
  });

  it("lets the higher-numbered file win, ACTIVITY_10 after ACTIVITY_2", () => {
    const parsed = parseZeppExport(
      buildZip([
        csv("ACTIVITY/ACTIVITY_10.csv", [ACTIVITY, "2026-10-02,1000,800,0,3"]),
        csv("ACTIVITY/ACTIVITY_2.csv", [ACTIVITY, "2026-10-02,200,160,0,2"]),
      ]),
      null,
    );
    expect(parsed.activity).toEqual([{ date: "2026-10-02", distanceM: 800, steps: 1000 }]);
  });

  it("reads a missing fat rate as none, as the real export writes it", () => {
    const parsed = parseZeppExport(
      buildZip([
        csv("BODY/BODY_1.csv", [
          BODY,
          "2021-08-24 05:48:14+0000,60.5,170.0,20.9,null,null,null,null,null,null",
        ]),
      ]),
      null,
    );
    expect(parsed.weighIns).toEqual([
      { bodyFatPct: null, measuredAt: "2021-08-24T05:48:14Z", weightKg: 60.5 },
    ]);
  });

  it("refuses a file with a broken required value instead of importing the rest", () => {
    const broken = (files: Array<{ data: Buffer; name: string }>) => {
      try {
        parseZeppExport(buildZip(files), null);
      } catch (error) {
        return error instanceof ZeppExportError ? error.reason : String(error);
      }
      return "no error";
    };
    expect(
      broken([
        csv("ACTIVITY/ACTIVITY_1.csv", [
          ACTIVITY,
          "2026-10-01,100,80,0,1",
          "2026-10-02,BROKEN,80,0,1",
        ]),
      ]),
    ).toBe("corrupt");
    expect(
      broken([
        csv("SLEEP/SLEEP_1.csv", [
          SLEEP,
          "2026-10-02,60,200,0,yesterday,2026-10-02 03:00:00+0000,40,",
        ]),
      ]),
    ).toBe("corrupt");
    expect(
      broken([
        csv("BODY/BODY_1.csv", [
          BODY,
          "2021-08-24 05:48:14+0000,null,170.0,20.9,null,null,null,null,null,null",
        ]),
      ]),
    ).toBe("corrupt");
    expect(broken([csv("ACTIVITY/ACTIVITY_1.csv", [ACTIVITY, "2026-13-45,100,80,0,1"])])).toBe(
      "corrupt",
    );
    expect(broken([csv("USER/USER_1.csv", ["userId", "1"])])).toBe("no_data");
  });
});
